
import numpy as np

# Create a 1D array
arr1 = np.array([10, 20, 30, 40, 50])
print("One-Dimensional Array:")
print(arr1)

# Create a 2D array
arr2 = np.array([[1, 2, 3],
                 [4, 5, 6]])
print("\nTwo-Dimensional Array:")
print(arr2)

# Create a 3D array
arr3 = np.array([[[1, 2], [3, 4]],
                 [[5, 6], [7, 8]]])
print("\nThree-Dimensional Array:")
print(arr3)